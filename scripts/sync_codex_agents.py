#!/usr/bin/env python3
"""sync_codex_agents.py — `.claude/agents/<name>.md` から `.codex/agents/<name>.toml` を生成する。

サブエージェント定義の原本は `.claude/agents/*.md`(Claude Code の形式)に 1 つだけ置く。
Codex の形式(`.codex/agents/*.toml`)はここで機械生成し、`validate_harness.py` が
「生成し直した結果と一致するか」を検査する。2 つの形式を手で保守すると必ずずれるため。

    python3 scripts/sync_codex_agents.py            # 日英ミラー両方を生成
    python3 scripts/sync_codex_agents.py --check    # 差分があれば exit 1(ファイルは変えない)
    python3 scripts/sync_codex_agents.py --root <dir>

Codex で表現できない Claude Code 側の設定は、指示文の冒頭に制約として書き下す:
  - `tools` に Edit / Write が無い          → 読取専用(Codex はエージェント単位のサンドボックスを持たない)
  - frontmatter の `scope-guard.sh <scope>` → 書込範囲(Codex にはエージェント単位のフックが無い)
  - `skills`                                → 先に読む skill
`model` は書かない(親セッションのモデルを継ぐ。固定するなら `.codex/config.toml` の `[agents]`)。
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

FM_RE = re.compile(r"\A---\n(.*?)\n---\n", re.S)
SCOPE_RE = re.compile(r"scope-guard\.sh\s+([a-z]+)")
WRITE_TOOLS = {"Edit", "Write", "NotebookEdit"}

TEXT = {
    "ja": {
        "generated": "# 生成物: scripts/sync_codex_agents.py が .claude/agents/{name}.md から生成する。直接編集せず、原本を直して再生成する",
        "head": "## Codex での制約(Claude Code 側の設定を指示として書き下したもの)",
        "readonly": "- 読取専用。ファイルを作成・編集・削除しない。Codex はエージェント単位のサンドボックスを持たないため、この制約は指示として守る",
        "scope": {
            "docs": "- 書き込んでよいのは `docs/` 配下と `project-config.md` だけ。それ以外への書込は親に差し戻す",
            "output": "- 書き込んでよいのは `output/` 配下だけ。それ以外への書込は親に差し戻す",
            "tests": "- 書き込んでよいのはテストファイル(`tests/` `test/` `e2e/` `__tests__/` `__mocks__/` `fixtures/` `testreport/`、"
                     "`*.test.*` `*.spec.*` `test_*.py` `*_test.py` `*_test.go`)だけ。それ以外への書込は親に差し戻す",
        },
        "skills": "- 作業の前に skill の手順を読む: {items}",
        "nospawn": "- 他のエージェントを起動しない(constitution ④: agent は agent を spawn しない)",
        "slash": "- 本文の `/name` は skill の呼び出しを指す。Codex では `$name` と読み替える",
    },
    "en": {
        "generated": "# Generated by scripts/sync_codex_agents.py from .claude/agents/{name}.md. Do not edit; fix the source and regenerate",
        "head": "## Constraints under Codex (Claude Code settings written out as instructions)",
        "readonly": "- Read-only. Do not create, edit or delete files. Codex has no per-agent sandbox, so follow this constraint as an instruction",
        "scope": {
            "docs": "- Write only under `docs/` and to `project-config.md`. Hand any other write back to the parent",
            "output": "- Write only under `output/`. Hand any other write back to the parent",
            "tests": "- Write only test files (`tests/` `test/` `e2e/` `__tests__/` `__mocks__/` `fixtures/` `testreport/`, "
                     "`*.test.*` `*.spec.*` `test_*.py` `*_test.py` `*_test.go`). Hand any other write back to the parent",
        },
        "skills": "- Read the skill procedure before working: {items}",
        "nospawn": "- Do not start other agents (constitution ④: an agent does not spawn an agent)",
        "slash": "- A `/name` in the body means a skill invocation. Under Codex read it as `$name`",
    },
}


def parse_agent(path: Path) -> tuple[dict, str]:
    """frontmatter の必要な項目だけを読む(YAML ライブラリに依存しない)。"""
    text = path.read_text(encoding="utf-8")
    m = FM_RE.match(text)
    if not m:
        raise ValueError(f"{path}: frontmatter がありません")
    fm_text, body = m.group(1), text[m.end():]
    fm: dict = {"skills": []}
    key = None
    for line in fm_text.split("\n"):
        top = re.match(r"^([A-Za-z_-]+):\s*(.*)$", line)
        if top:
            key, val = top.group(1), top.group(2).strip()
            if key == "skills":
                fm["skills"] = []
            elif key in ("name", "description", "tools", "effort"):
                fm[key] = val.strip("\"'") if key != "description" else val
            continue
        item = re.match(r"^\s+-\s+(\S+)\s*$", line)
        if item and key == "skills":
            fm["skills"].append(item.group(1))
    scope = SCOPE_RE.search(fm_text)
    fm["scope"] = scope.group(1) if scope else ""
    tools = {t.strip() for t in fm.get("tools", "").split(",") if t.strip()}
    fm["readonly"] = not (tools & WRITE_TOOLS)
    return fm, body.strip("\n")


def render(md_path: Path, lang: str) -> str:
    fm, body = parse_agent(md_path)
    t = TEXT[lang]
    name = fm["name"]
    if "'''" in body:
        raise ValueError(f"{md_path}: 本文に ''' があり、TOML の複数行リテラル文字列にできません")
    lines = [t["head"], ""]
    if fm["readonly"]:
        lines.append(t["readonly"])
    elif fm["scope"] in t["scope"]:
        lines.append(t["scope"][fm["scope"]])
    if fm["skills"]:
        items = " / ".join(f"`${s}`(`.agents/skills/{s}/SKILL.md`)" for s in fm["skills"])
        lines.append(t["skills"].format(items=items))
    lines.append(t["nospawn"])
    lines.append(t["slash"])
    out = [
        t["generated"].format(name=name),
        f"name = {json.dumps(name, ensure_ascii=False)}",
        f"description = {json.dumps(fm.get('description', ''), ensure_ascii=False)}",
    ]
    if fm.get("effort"):
        out.append(f"model_reasoning_effort = {json.dumps(fm['effort'])}")
    out.append("developer_instructions = '''")
    out.append("\n".join(lines))
    out.append("")
    out.append(body)
    out.append("'''")
    return "\n".join(out) + "\n"


def detect_lang(root: Path) -> str:
    """ミラーの言語。ディレクトリ名で決まらないとき(テストが一時ディレクトリへ写したとき)は本文の文字で判定する。"""
    if root.name.endswith("-en"):
        return "en"
    if root.name == "project-blueprint":
        return "ja"
    sample = ""
    for md in sorted((root / ".claude" / "agents").glob("*.md")):
        sample += md.read_text(encoding="utf-8")[:2000]
    cjk = sum(1 for ch in sample if "\u3040" <= ch <= "\u30ff" or "\u4e00" <= ch <= "\u9fff")
    return "ja" if sample and cjk / len(sample) > 0.02 else "en"


def expected_files(root: Path) -> dict[Path, str]:
    """root(ミラー 1 つ)について、生成されるべき {toml パス: 内容} を返す。"""
    lang = detect_lang(root)
    src = root / ".claude" / "agents"
    out: dict[Path, str] = {}
    if not src.is_dir():
        return out
    for md in sorted(src.glob("*.md")):
        if md.name == "README.md":
            continue
        out[root / ".codex" / "agents" / (md.stem + ".toml")] = render(md, lang)
    return out


def main() -> int:
    args = sys.argv[1:]
    check = "--check" in args
    repo = Path(__file__).resolve().parent.parent
    roots = [repo / "project-blueprint", repo / "project-blueprint-en"]
    if "--root" in args:
        roots = [Path(args[args.index("--root") + 1]).resolve()]
    stale = 0
    for root in roots:
        want = expected_files(root)
        dst_dir = root / ".codex" / "agents"
        for path, content in want.items():
            current = path.read_text(encoding="utf-8") if path.is_file() else None
            if current == content:
                continue
            stale += 1
            if check:
                print(f"STALE  {path.relative_to(root.parent)}")
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8")
                print(f"wrote  {path.relative_to(root.parent)}")
        if dst_dir.is_dir():
            for extra in sorted(dst_dir.glob("*.toml")):
                if extra not in want:
                    stale += 1
                    print(f"{'ORPHAN' if check else 'orphan (原本なし。手で消す)'}  {extra.relative_to(root.parent)}")
    if check and stale:
        print(f"{stale} 件が原本とずれています。python3 scripts/sync_codex_agents.py で再生成してください")
        return 1
    if not check:
        print(f"done ({stale} 件を更新)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
